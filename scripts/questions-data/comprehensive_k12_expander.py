        ("پروتئین‌ها از زنجیره‌ای از کدام زیرواحدهای ساختاری تشکیل شده‌اند؟", ["آمینواسیدها", "گلوکز", "اسیدهای چرب", "نوکلئوتیدها"], 0, 12, "biology", "مونومرهای سازنده پروتئین آمینواسیدها هستند."),
        ("مقاومت الکتریکی یک رسانا با کدام عامل رابطه مستقیم دارد؟", ["طول رسانا", "سطح مقطع رسانا", "جنس عایق", "ولتاژ دو سر"], 0, 11, "physics", "با افزایش طول رسانا، مقاومت الکتریکی به طور مستقیم زیاد می‌شود.")
