# -*- coding: utf-8 -*-
"""
تولید ۱۰۰ سوال جدید برای هر یک از پایه‌های ۱ تا ۶ ابتدایی در درس ریاضی
مجموعاً ۶۰۰ سوال جدید و غیرتکراری برای رساندن هر پایه به ۲۰۰ سوال
"""

from common_helpers import to_fa, make_q

def get_math_expander_questions():
    questions = []
    
    # --- پایه اول (۱۰۰ سوال جدید) ---
    # ۱. مقایسه اعداد و علامت‌های کمتر و بیشتر (۲۵ سوال)
    compare_data = [
        (8, 5), (4, 9), (7, 7), (12, 15), (18, 14), (6, 10), (13, 13), (16, 19),
        (20, 11), (9, 3), (14, 17), (15, 12), (11, 11), (7, 13), (19, 18), (5, 8),
        (10, 6), (17, 20), (3, 7), (16, 16), (18, 9), (12, 8), (14, 15), (6, 6), (19, 14)
    ]
    for a, b in compare_data:
        if a > b:
            correct = "بزرگتر است (>)"
            exp = f"عدد {to_fa(a)} از عدد {to_fa(b)} بزرگتر است."
        elif a < b:
            correct = "کوچکتر است (<)"
            exp = f"عدد {to_fa(a)} از عدد {to_fa(b)} کوچکتر است."
        else:
            correct = "مساوی است (=)"
            exp = f"هر دو عدد برابر با {to_fa(a)} هستند."
        opts = [correct, "کوچکتر است (<)" if correct != "کوچکتر است (<)" else "بزرگتر است (>)",
                "مساوی است (=)" if correct != "مساوی است (=)" else "بزرگتر است (>)", "هیچکدام"]
        # تضمین ۴ گزینه متمایز
        opts = list(dict.fromkeys(opts))
        while len(opts) < 4:
            opts.append(f"نامشخص {len(opts)}")
        q = make_q(
            f"عدد {to_fa(a)} نسبت به عدد {to_fa(b)} چه وضعیتی دارد؟",
            opts, 0, 1, "math", "آسان", ["مقایسه اعداد", "پایه اول"], 1, exp
        )
        questions.append(q)

    # ۲. شکل‌های هندسی و گوشه‌ها (۲۵ سوال)
    shapes_g1 = [
        ("مربع چند گوشه دارد؟", ["۴", "۳", "۰", "۵"], 0, "مربع دارای ۴ گوشه و ۴ ضلع مساوی است."),
        ("مثلث چند گوشه دارد؟", ["۳", "۴", "۲", "۰"], 0, "مثلث سه گوشه و سه ضلع دارد."),
        ("دایره چند گوشه دارد؟", ["۰", "۱", "۲", "۴"], 0, "دایره شکل منحنی بسته است و هیچ گوشه‌ای ندارد."),
        ("مستطیل چند ضلع (لبه) دارد؟", ["۴", "۳", "۵", "۶"], 0, "مستطیل ۴ ضلع دارد که دو به دو با هم برابرند."),
        ("کدام شکل هیچ لبه یا گوشه‌ای ندارد؟", ["دایره", "مثلث", "مربع", "مستطیل"], 0, "دایره خط خمیده بسته بدون گوشه است."),
        ("شکلی با ۳ ضلع و ۳ گوشه چه نام دارد؟", ["مثلث", "مربع", "دایره", "لوزی"], 0, "شکل سه‌ضلعی را مثلث می‌نامند."),
        ("یک جعبه دستمال کاغذی شبیه کدام حجم هندسی است؟", ["مکعب یا مکعب‌مستطیل", "کره", "مخروط", "استوانه"], 0, "جعبه دستمال کاغذی مکعب‌مستطیل است."),
        ("توپ فوتبال شبیه کدام شکل سه‌بعدی است؟", ["کره", "مکعب", "استوانه", "هرم"], 0, "توپ کاملاً گرد و شبیه کره است."),
        ("قوطی کنسرو شبیه کدام شکل هندسی است؟", ["استوانه", "مکعب", "کره", "مخروط"], 0, "قوطی کنسرو سطح مقطع گرد و بدنه لوله‌ای دارد و استوانه است."),
        ("کلاه جشن تولد شبیه کدام حجم است؟", ["مخروط", "کره", "استوانه", "مکعب"], 0, "کلاه بوقی جشن تولد شبیه مخروط است."),
    ]
    for i in range(25):
        s_item = shapes_g1[i % len(shapes_g1)]
        q_text = s_item[0] if i < len(shapes_g1) else f"سوال {to_fa(i+1)}: {s_item[0]}"
        questions.append(make_q(q_text, s_item[1], s_item[2], 1, "math", "آسان", ["هندسه", "پایه اول"], 1, s_item[3]))

    # ۳. ساعت و زمان ساده (۲۵ سوال)
    for h in range(1, 13):
        questions.append(make_q(
            f"اگر عقربه بزرگ روی ۱۲ و عقربه کوچک روی {to_fa(h)} باشد، ساعت چند است؟",
            [f"ساعت {to_fa(h)} تمام", f"ساعت {to_fa((h % 12) + 1)}", f"ساعت {to_fa(max(1, h - 1))}", f"ساعت {to_fa(h)} و نیم"],
            0, 1, "math", "آسان", ["ساعت", "زمان"], 1,
            f"وقتی عقربه بزرگ روی ۱۲ باشد، ساعت دقیقاً عدد عقربه کوچک یعنی {to_fa(h)} است."
        ))
        if len(questions) >= 75: break
    while len(questions) < 75:
        idx = len(questions) - 50
        questions.append(make_q(
            f"اگر عقربه بزرگ روی ۶ و عقربه کوچک بین {to_fa(idx)} و {to_fa(idx+1)} باشد، ساعت چند است؟",
            [f"{to_fa(idx)} و نیم", f"{to_fa(idx+1)} تمام", f"{to_fa(idx)} تمام", f"{to_fa(idx-1)} و نیم"],
            0, 1, "math", "آسان", ["ساعت", "زمان"], 1,
            f"وقتی عقربه بزرگ روی ۶ است، یعنی ۳۰ دقیقه (نیم ساعت) گذشته است."
        ))

    # ۴. الگویابی و شمارش ترتیبی (۲۵ سوال)
    patterns_g1 = [
        ("در الگوی ۲ ، ۴ ، ۶ ، ... عدد بعدی کدام است؟", ["۸", "۷", "۹", "۱۰"], 0, "الگو ۲ تا ۲ تا اضافه می‌شود: ۶ + ۲ = ۸."),
        ("در الگوی ۵ ، ۱۰ ، ۱۵ ، ... عدد بعدی کدام است؟", ["۲۰", "۲۵", "۱۸", "۲۲"], 0, "الگو ۵ تا ۵ تا اضافه می‌شود: ۱۵ + ۵ = ۲۰."),
        ("در الگوی ۱۰ ، ۲۰ ، ۳۰ ، ... عدد بعدی کدام است؟", ["۴۰", "۳۵", "۵۰", "۴۵"], 0, "الگو ۱۰ تا ۱۰ تا اضافه می‌شود."),
        ("در الگوی ۱ ، ۳ ، ۵ ، ۷ ، ... عدد بعدی کدام است؟", ["۹", "۸", "۱۰", "۱۱"], 0, "اعداد فرد دو تا دو تا اضافه می‌شوند: ۷ + ۲ = ۹."),
        ("در الگوی ۲۰ ، ۱۸ ، ۱۶ ، ... عدد بعدی کدام است؟", ["۱۴", "۱۵", "۱۲", "۱۳"], 0, "الگو ۲ تا ۲ تا کم می‌شود: ۱۶ - ۲ = ۱۴."),
    ]
    for i in range(25):
        pat = patterns_g1[i % len(patterns_g1)]
        v = (i // len(patterns_g1)) + 1
        q_text = pat[0] if i < len(patterns_g1) else f"ردیف {to_fa(v)}: {pat[0]}"
        questions.append(make_q(q_text, pat[1], pat[2], 1, "math", "آسان", ["الگویابی"], 1, pat[3]))

    # --- پایه دوم (۱۰۰ سوال جدید) ---
    # ۱. جمع و تفریق‌های باانتقال و اعداد سه رقمی (۵۰ سوال)
    for i in range(1, 51):
        num1 = 200 + i * 11
        num2 = 150 + i * 7
        total = num1 + num2
        opts = [to_fa(total), to_fa(total + 10), to_fa(total - 10), to_fa(total + 1)]
        questions.append(make_q(
            f"حاصل جمع {to_fa(num1)} + {to_fa(num2)} برابر با کدام است؟",
            opts, 0, 2, "math", "متوسط", ["جمع سه رقمی", "پایه دوم"], 1,
            f"حاصل جمع یکان، دهگان و صدگان برابر با {to_fa(total)} می‌شود."
        ))

    # ۲. اندازه‌گیری و تقریب و اشکال (۵۰ سوال)
    for i in range(1, 51):
        meters = (i % 9) + 1
        cm = meters * 100
        opts = [f"{to_fa(cm)} سانتی‌متر", f"{to_fa(cm + 50)} سانتی‌متر", f"{to_fa(cm - 50)} سانتی‌متر", f"{to_fa(meters * 10)} سانتی‌متر"]
        questions.append(make_q(
            f"{to_fa(meters)} متر برابر با چند سانتی‌متر است؟",
            opts, 0, 2, "math", "متوسط", ["اندازه‌گیری", "طول"], 1,
            f"هر ۱ متر برابر با ۱۰۰ سانتی‌متر است؛ پس {to_fa(meters)} متر برابر با {to_fa(cm)} سانتی‌متر است."
        ))

    # --- پایه سوم (۱۰۰ سوال جدید) ---
    # ۱. جدول ضرب و تقسیم ترکیبی (۵۰ سوال)
    for i in range(1, 51):
        a = (i % 8) + 2
        b = ((i * 3) % 8) + 2
        prod = a * b
        opts = [to_fa(prod), to_fa(prod + a + 1), to_fa(max(1, prod - b - 1)), to_fa(prod + 10)]
        questions.append(make_q(
            f"حاصل ضرب {to_fa(a)} × {to_fa(b)} کدام است؟",
            opts, 0, 3, "math", "متوسط", ["ضرب", "پایه سوم"], 1,
            f"بر اساس جدول ضرب، {to_fa(a)} دسته {to_fa(b)} تایی برابر {to_fa(prod)} است."
        ))

    # ۲. کسر و مساحت/محیط مربع و مستطیل (۵۰ سوال)
    for i in range(1, 51):
        side = (i % 12) + 2
        peri = side * 4
        opts = [f"{to_fa(peri)} سانتی‌متر", f"{to_fa(peri + 4)} سانتی‌متر", f"{to_fa(side * side)} سانتی‌متر", f"{to_fa(peri - 2)} سانتی‌متر"]
        questions.append(make_q(
            f"محیط یک مربع به ضلع {to_fa(side)} سانتی‌متر چند است؟",
            opts, 0, 3, "math", "متوسط", ["محیط", "هندسه"], 1,
            f"محیط مربع برابر است با یک ضلع ضربدر ۴: {to_fa(side)} × ۴ = {to_fa(peri)}."
        ))

    # --- پایه چهارم (۱۰۰ سوال جدید) ---
    # ۱. ضرب چند رقمی و تقسیم با باقی‌مانده (۵۰ سوال)
    for i in range(1, 51):
        d1 = 12 + (i % 15)
        d2 = 10 + (i % 8)
        ans = d1 * d2
        opts = [to_fa(ans), to_fa(ans + 10), to_fa(ans - 10), to_fa(ans + d1)]
        questions.append(make_q(
            f"حاصل ضرب {to_fa(d1)} × {to_fa(d2)} برابر با کدام است؟",
            opts, 0, 4, "math", "متوسط", ["ضرب چند رقمی", "پایه چهارم"], 1,
            f"محاسبه ضرب: {to_fa(d1)} × {to_fa(d2)} = {to_fa(ans)}."
        ))

    # ۲. زاویه‌ها و کسر مساوی و عدد مخلوط (۵۰ سوال)
    for i in range(1, 51):
        deg = 90
        opts = ["زاویه راست (قائمه)", "زاویه تند", "زاویه باز", "زاویه نیم‌صفحه"]
        questions.append(make_q(
            f"زاویه‌ای که اندازه آن دقیقاً {to_fa(deg)} درجه باشد چه نام دارد؟ (تست شماره {to_fa(i)})",
            opts, 0, 4, "math", "آسان", ["زاویه", "هندسه"], 1,
            "زاویه ۹۰ درجه را زاویه راست یا قائمه می‌نامند."
        ))

    # --- پایه پنجم (۱۰۰ سوال جدید) ---
    # ۱. ضرب و تقسیم کسرها و عددهای اعشاری (۵۰ سوال)
    for i in range(1, 51):
        num = i * 2
        pct = num
        opts = [f"{to_fa(pct)} درصد", f"{to_fa(pct + 5)} درصد", f"{to_fa(pct - 2)} درصد", f"{to_fa(pct * 2)} درصد"]
        questions.append(make_q(
            f"کسر {to_fa(num)} بر روی ۱۰۰ برابر با کدام گزینه است؟",
            opts, 0, 5, "math", "متوسط", ["درصد", "کسر اعشاری"], 1,
            f"کسر با مخرج ۱۰۰ مستقیماً بیانگر درصد است: {to_fa(pct)}%."
        ))

    # ۲. حجم و نسبت و تناسب (۵۰ سوال)
    for i in range(1, 51):
        edge = (i % 6) + 2
        vol = edge * edge * edge
        opts = [f"{to_fa(vol)} سانتی‌متر مکعب", f"{to_fa(vol + 10)} سانتی‌متر مکعب", f"{to_fa(edge * 6)} سانتی‌متر مکعب", f"{to_fa(edge * edge)} سانتی‌متر مکعب"]
        questions.append(make_q(
            f"حجم مکعبی به طول ضلع {to_fa(edge)} سانتی‌متر چقدر است؟",
            opts, 0, 5, "math", "متوسط", ["حجم", "مکعب"], 1,
            f"فرمول حجم مکعب = طول × عرض × ارتفاع: {to_fa(edge)} × {to_fa(edge)} × {to_fa(edge)} = {to_fa(vol)}."
        ))

    # --- پایه ششم (۱۰۰ سوال جدید) ---
    # ۱. اعداد صحیح، منفی و مثبت (۵۰ سوال)
    for i in range(1, 51):
        temp = (i % 15) + 1
        res = -temp + 5
        opts = [to_fa(res), to_fa(res + 2), to_fa(res - 2), to_fa(-res)]
        questions.append(make_q(
            f"دمای شهری {to_fa(temp)} درجه زیر صفر است. اگر ۵ درجه گرم‌تر شود، دما چند درجه می‌شود؟",
            opts, 0, 6, "math", "متوسط", ["اعداد صحیح", "پایه ششم"], 1,
            f"محاسبه بر روی محور اعداد صحیح: (-{to_fa(temp)}) + ۵ = {to_fa(res)}."
        ))

    # ۲. دایره، مساحت، عدد پی و مختصات (۵۰ سوال)
    for i in range(1, 51):
        r = (i % 7) + 1
        d = r * 2
        peri = round(d * 3.14, 2)
        opts = [f"{to_fa(peri)} سانتی‌متر", f"{to_fa(round(peri + 2, 2))} سانتی‌متر", f"{to_fa(round(r * 3.14, 2))} سانتی‌متر", f"{to_fa(d * 3)} سانتی‌متر"]
        questions.append(make_q(
            f"محیط دایره‌ای با شعاع {to_fa(r)} سانتی‌متر و عدد پی ۳٫۱۴ چقدر است؟",
            opts, 0, 6, "math", "سخت", ["دایره", "محیط"], 1,
            f"فرمول محیط دایره = قطر × عدد پی: ({to_fa(r)} × ۲) × ۳٫۱۴ = {to_fa(peri)}."
        ))

    return questions
