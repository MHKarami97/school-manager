import random

def make_q(text, options, correct_idx, grade, difficulty="متوسط", tags=None, score=1, explanation=""):
    options = [str(opt).strip() for opt in options]
    correct_val = options[correct_idx]
    
    shuffled = options[:]
    random.shuffle(shuffled)
    new_correct_idx = shuffled.index(correct_val)
    
    return {
        "id": f"per-g{grade}-{random.randint(100000, 999999)}",
        "text": text.strip(),
        "type": "multiple-choice",
        "options": shuffled,
        "correctAnswer": str(new_correct_idx),
        "courseId": "persian-reading",
        "grade": grade,
        "difficulty": difficulty,
        "tags": tags or ["فارسی"],
        "suggestedScore": score,
        "explanation": explanation.strip() or f"پاسخ صحیح گزینه {new_correct_idx + 1} یعنی «{correct_val}» است.",
    }

