export function getChoganGameById(id: string): ChoganGame | undefined {
  return CHOGAN_GAMES.find((g) => g.id === id)
}

export function getChoganGamesByCategory(category: 'all' | GameCategory): ChoganGame[] {
  if (category === 'all') return CHOGAN_GAMES
  return CHOGAN_GAMES.filter((g) => g.category === category)
}

export function searchChoganGames(query: string, category: 'all' | GameCategory = 'all'): ChoganGame[] {
  const q = query.trim().toLowerCase()
  return CHOGAN_GAMES.filter((g) => {
    if (category !== 'all' && g.category !== category) return false
    if (!q) return true
    return (
      g.nameFa.toLowerCase().includes(q) ||
      g.nameEn.toLowerCase().includes(q) ||
      g.summaryFa.toLowerCase().includes(q) ||
      g.id.toLowerCase().includes(q)
    )
  })
}
