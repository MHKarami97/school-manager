        ("بن مضارع فعل «می‌نویسد» کدام است؟", ["نویس", "نوشت", "نویسنده", "نوشتن"], 0, "با حذف «بـ» از فعل امر بن مضارع به دست می‌آید: بنویس -> نویس."),
        ("کدام ضمیر شخصی منفصل است؟", ["ما", "-ِمان", "-َت", "-َش"], 0, "ضمایر منفصل جدا نوشته می‌شوند: من، تو، او، ما، شما، ایشان."),
        ("کدام دو واژه با یکدیگر «متضاد» هستند؟", ["فراز و نشیب", "آگاهی و خرد", "علم و دانش", "دوست و رفیق"], 0, "فراز (بالا) و نشیب (پایین) ضد یکدیگرند.")
