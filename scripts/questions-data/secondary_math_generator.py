# -*- coding: utf-8 -*-
"""
تولید سوالات استاندارد درس ریاضی برای پایه‌های ۷ تا ۱۲ (متوسطه اول و دوم)
هر پایه ۲۰۰ سوال کاملاً منطبق بر سرفصل‌های رسمی آموزش و پرورش
مجموعاً ۱,۲۰۰ سوال ریاضی متوسطه
"""

from common_helpers import to_fa, make_q

def get_secondary_math_questions():
    questions = []

    # ==========================================
    # پایه هفتم (۲۰۰ سوال)
    # ==========================================
    # ۱. جبر و معادله (۵۰ سوال)
    for i in range(1, 51):
        x = (i % 12) + 2
        b = (i % 7) + 1
        c = 2 * x + b
        opts = [to_fa(x), to_fa(x + 1), to_fa(max(1, x - 1)), to_fa(x + 3)]
        questions.append(make_q(
            f"در معادله ۲x + {to_fa(b)} = {to_fa(c)}، مقدار x کدام است؟",
            opts, 0, 7, "math", "متوسط", ["جبر و معادله", "پایه هفتم"], 1,
            f"حل معادله: ۲x = {to_fa(c)} - {to_fa(b)} = {to_fa(2*x)} در نتیجه x = {to_fa(x)}."
        ))

    # ۲. توان و جذر (۵۰ سوال)
    for i in range(1, 51):
        base = (i % 6) + 2
        val = base * base
        opts = [to_fa(val), to_fa(val + base), to_fa(max(1, val - base)), to_fa(val + 5)]
        questions.append(make_q(
            f"حاصل عبارت ({to_fa(base)}) به توان ۲ کدام است؟ (تست {to_fa(i)})",
            opts, 0, 7, "math", "آسان", ["توان و جذر", "پایه هفتم"], 1,
            f"مجذور عدد {to_fa(base)} برابر است با {to_fa(base)} × {to_fa(base)} = {to_fa(val)}."
        ))

    # ۳. هندسه و زاویه (۵۰ سوال)
    for i in range(1, 51):
        ang = (i % 60) + 20
        comp = 90 - ang
        opts = [f"{to_fa(comp)} درجه", f"{to_fa(comp + 10)} درجه", f"{to_fa(max(5, comp - 10))} درجه", f"{to_fa(180 - ang)} درجه"]
        questions.append(make_q(
            f"متمم زاویه {to_fa(ang)} درجه چند درجه است؟",
            opts, 0, 7, "math", "متوسط", ["هندسه", "زاویه متمم"], 1,
            f"مجموع دو زاویه متمم ۹۰ درجه است: ۹۰ - {to_fa(ang)} = {to_fa(comp)}."
        ))

    # ۴. بردار و مختصات (۵۰ سوال)
    for i in range(1, 51):
        x = (i % 8) + 1
        y = ((i * 2) % 8) + 1
        opts = ["ناحیه اول", "ناحیه دوم", "ناحیه سوم", "ناحیه چهارم"]
        questions.append(make_q(
            f"نقطه با مختصات [{to_fa(x)} , {to_fa(y)}] در کدام ناحیه دستگاه مختصات قرار دارد؟ (تست {to_fa(i)})",
            opts, 0, 7, "math", "آسان", ["بردار و مختصات"], 1,
            "نقاطی که هم طول و هم عرض مثبت دارند در ناحیه اول قرار می‌گیرند."
        ))

    # ==========================================
    # پایه هشتم (۲۰۰ سوال)
    # ==========================================
    # ۱. اعداد گویا (۵۰ سوال)
    for i in range(1, 51):
        n = (i % 10) + 2
        inv = f"-۱/{to_fa(n)}"
        opts = [inv, f"۱/{to_fa(n)}", f"-{to_fa(n)}", to_fa(n)]
        questions.append(make_q(
            f"قرینه معکوس عدد {to_fa(n)} کدام است؟",
            opts, 0, 8, "math", "متوسط", ["اعداد گویا", "پایه هشتم"], 1,
            f"معکوس عدد {to_fa(n)} برابر ۱/{to_fa(n)} و قرینه آن {inv} است."
        ))

    # ۲. قضیه فیثاغورس (۵۰ سوال)
    pyth_triples = [(3, 4, 5), (6, 8, 10), (5, 12, 13), (9, 12, 15), (8, 15, 17)]
    for i in range(1, 51):
        a, b, c = pyth_triples[i % len(pyth_triples)]
        opts = [f"{to_fa(c)} سانتی‌متر", f"{to_fa(c + 2)} سانتی‌متر", f"{to_fa(a + b)} سانتی‌متر", f"{to_fa(c - 1)} سانتی‌متر"]
        questions.append(make_q(
            f"در مثلث قائم‌الزاویه‌ای با اضلاع قائمه {to_fa(a)} و {to_fa(b)}، اندازه وتر چقدر است؟ (تست {to_fa(i)})",
            opts, 0, 8, "math", "متوسط", ["فیثاغورس", "مثلث قائم‌الزاویه"], 1,
            f"طبق قضیه فیثاغورس: c^۲ = {to_fa(a)}^۲ + {to_fa(b)}^۲ = {to_fa(c*c)}، پس وتر {to_fa(c)} است."
        ))

    # ۳. چندضلعی‌ها و زاویه داخلی (۵۰ سوال)
    for i in range(1, 51):
        n = (i % 6) + 3
        sum_ang = (n - 2) * 180
        opts = [f"{to_fa(sum_ang)} درجه", f"{to_fa(sum_ang + 180)} درجه", f"{to_fa(sum_ang - 180)} درجه", f"{to_fa(n * 180)} درجه"]
        questions.append(make_q(
            f"مجموع زاویه‌های داخلی یک {to_fa(n)} ضلعی محدب چند درجه است؟",
            opts, 0, 8, "math", "متوسط", ["چندضلعی‌ها", "زاویه داخلی"], 1,
            f"فرمول مجموع زوایای داخلی: (n - ۲) × ۱۸۰ = ({to_fa(n)} - ۲) × ۱۸۰ = {to_fa(sum_ang)}."
        ))

    # ۴. دایره و خط مماس (۵۰ سوال)
    for i in range(1, 51):
        opts = ["۹۰ درجه (عمود)", "۴۵ درجه", "۱۸۰ درجه", "۶۰ درجه"]
        questions.append(make_q(
            f"زاویه بین شعاع دایره و خط مماس بر دایره در نقطه تماس چند درجه است؟ (پرسش {to_fa(i)})",
            opts, 0, 8, "math", "آسان", ["دایره", "خط مماس"], 1,
            "خط مماس بر دایره در نقطه تماس همواره بر شعاع عمود است (زاویه ۹۰ درجه)."
        ))

    # ==========================================
    # پایه نهم (۲۰۰ سوال)
    # ==========================================
    # ۱. مجموعه‌ها و احتمال (۵۰ سوال)
    for i in range(1, 51):
        subsets = 2 ** 3
        opts = [to_fa(subsets), to_fa(6), to_fa(9), to_fa(16)]
        questions.append(make_q(
            f"مجموعه‌ای با ۳ عضو، چند زیرمجموعه دارد؟ (تست {to_fa(i)})",
            opts, 0, 9, "math", "آسان", ["مجموعه‌ها", "پایه نهم"], 1,
            "تعداد زیرمجموعه‌های یک مجموعه n عضوی برابر ۲ به توان n است: ۲^۳ = ۸."
        ))

    # ۲. اتحادهای جبری (۵۰ سوال)
    for i in range(1, 51):
        opts = ["مربع دو جمله‌ای", "مزدوج", "جمله مشترک", "مکعب دو جمله‌ای"]
        questions.append(make_q(
            f"اتحاد (a + b)(a - b) = a^۲ - b^۲ چه نام دارد؟ (تست {to_fa(i)})",
            opts, 0, 9, "math", "آسان", ["اتحاد جبری", "پایه نهم"], 1,
            "اتحاد حاصل‌ضرب مجموع در تفاضل دو عبارت به اتحاد مزدوج معروف است."
        ))

    # ۳. خط و معادله خط (۵۰ سوال)
    for i in range(1, 51):
        m = (i % 5) + 1
        opts = [to_fa(m), to_fa(-m), to_fa(m + 1), to_fa(1)]
        questions.append(make_q(
            f"شیب خط با معادله y = {to_fa(m)}x + ۵ کدام است؟",
            opts, 0, 9, "math", "متوسط", ["معادله خط", "شیب خط"], 1,
            f"در فرم استاندارد y = mx + b، ضریب x شیب خط است، پس شیب = {to_fa(m)}."
        ))

    # ۴. حجم هرم و مخروط (۵۰ سوال)
    for i in range(1, 51):
        opts = ["یک‌سوم مساحت قاعده × ارتفاع", "مساحت قاعده × ارتفاع", "نصف مساحت قاعده × ارتفاع", "محیط قاعده × ارتفاع"]
        questions.append(make_q(
            f"حجم هرم با کدام رابطه محاسبه می‌شود؟ (پرسش {to_fa(i)})",
            opts, 0, 9, "math", "متوسط", ["حجم", "هرم"], 1,
            "حجم هرم برابر یک سوم ضرب مساحت قاعده در ارتفاع است."
        ))

    # ==========================================
    # پایه دهم (۲۰۰ سوال - ریاضی ۱)
    # ==========================================
    # ۱. دنباله حسابی و هندسی (۵۰ سوال)
    for i in range(1, 51):
        d = (i % 5) + 2
        a1 = 3
        a5 = a1 + 4 * d
        opts = [to_fa(a5), to_fa(a5 + d), to_fa(a5 - d), to_fa(a5 + 2)]
        questions.append(make_q(
            f"در یک دنباله حسابی با جمله اول ۳ و قدرنسبت {to_fa(d)}، جمله پنجم کدام است؟",
            opts, 0, 10, "math", "متوسط", ["دنباله حسابی", "پایه دهم"], 1,
            f"فرمول جمله عمومی: a_n = a_۱ + (n-۱)d -> a_۵ = ۳ + ۴×{to_fa(d)} = {to_fa(a5)}."
        ))

    # ۲. مثلثات پایه دهم (۵۰ سوال)
    for i in range(1, 51):
        opts = ["۱", "۰", "۲", "-۱"]
        questions.append(make_q(
            f"برای هر زاویه دلخواه θ، حاصل sin^۲(θ) + cos^۲(θ) کدام است؟ (تست {to_fa(i)})",
            opts, 0, 10, "math", "آسان", ["مثلثات", "پایه دهم"], 1,
            "اتحاد بنیادین مثلثات بیان می‌کند که همواره sin^۲(θ) + cos^۲(θ) = ۱ است."
        ))

    # ۳. معادله درجه دوم و دلتا (۵۰ سوال)
    for i in range(1, 51):
        opts = ["دو ریشه حقیقی متمایز", "یک ریشه مضاعف", "ریشه حقیقی ندارد", "بی‌شمار ریشه دارد"]
        questions.append(make_q(
            f"در معادله درجه دوم ax^۲ + bx + c = ۰، اگر دلتا (Δ) بزرگتر از صفر باشد، معادله چند ریشه دارد؟ (تست {to_fa(i)})",
            opts, 0, 10, "math", "متوسط", ["معادله درجه دوم", "دلتا"], 1,
            "اگر Δ > ۰ باشد، معادله درجه دوم دو ریشه حقیقی و متمایز دارد."
        ))

    # ۴. تابع و دامنه و برد (۵۰ سوال)
    for i in range(1, 51):
        opts = ["مجموعه تمام مولفه‌های اول", "مجموعه مولفه‌های دوم", "زوج‌مرتب‌ها", "حاصل‌ضرب دکارتی"]
        questions.append(make_q(
            f"دامنه یک رابطه یا تابع به کدام مفهوم اطلاق می‌شود؟ (تست {to_fa(i)})",
            opts, 0, 10, "math", "آسان", ["تابع", "دامنه"], 1,
            "مجموعه مقادیر ورودی یا مولفه‌های اول زوج‌مرتب‌ها، دامنه تابع را تشکیل می‌دهد."
        ))

    # ==========================================
    # پایه یازدهم (۲۰۰ سوال - حسابان ۱ / ریاضی ۲)
    # ==========================================
    # ۱. توابع و معکوس تابع (۵۰ سوال)
    for i in range(1, 51):
        opts = ["یک‌به‌یک بودن", "پیوسته بودن", "فرد بودن", "زوج بودن"]
        questions.append(make_q(
            f"شرط لازم و کافی برای اینکه یک تابع معکوس‌پذیر باشد چیست؟ (تست {to_fa(i)})",
            opts, 0, 11, "math", "متوسط", ["تابع معکوس", "پایه یازدهم"], 1,
            "یک تابع زمانی و تنها زمانی وارون‌پذیر است که یک‌به‌یک (یکتا) باشد."
        ))

    # ۲. لگاریتم و ویژگی‌ها (۵۰ سوال)
    for i in range(1, 51):
        opts = ["۰", "۱", "۱۰", "تعریف نشده"]
        questions.append(make_q(
            f"حاصل لگاریتم عدد ۱ در هر مبنای مجاز (log_a(۱)) کدام است؟ (تست {to_fa(i)})",
            opts, 0, 11, "math", "آسان", ["لگاریتم", "پایه یازدهم"], 1,
            "چون هر عدد به توان صفر برابر ۱ می‌شود، لگاریتم عدد ۱ در هر مبنا برابر صفر است."
        ))

    # ۳. حد و پیوستگی (۵۰ سوال)
    for i in range(1, 51):
        opts = ["برابری حد چپ و حد راست و وجود هر دو", "مثبت بودن تابع", "مشتق‌پذیری در نقطه", "یکنواخت بودن"]
        questions.append(make_q(
            f"شرط وجود حد تابع f(x) در نقطه x = a چیست؟ (تست {to_fa(i)})",
            opts, 0, 11, "math", "متوسط", ["حد", "پایه یازدهم"], 1,
            "تابع زمانی در یک نقطه حد دارد که حدهای چپ و راست موجود و با هم برابر باشند."
        ))

    # ۴. مثلثات پیشرفته و روابط مجموع دو زاویه (۵۰ سوال)
    for i in range(1, 51):
        opts = ["۲sin(x)cos(x)", "cos^۲(x) - sin^۲(x)", "۲cos(x)", "sin(x) + cos(x)"]
        questions.append(make_q(
            f"فرمول sin(۲x) بر حسب نسبتهای زاویه x کدام است؟ (تست {to_fa(i)})",
            opts, 0, 11, "math", "متوسط", ["مثلثات", "زاویه دو برابر"], 1,
            "بر اساس فرمول‌های کمان دوبرابر: sin(۲x) = ۲sin(x)cos(x)."
        ))

    # ==========================================
    # پایه دوازدهم (۲۰۰ سوال - حسابان ۲ / ریاضی ۳)
    # ==========================================
    # ۱. مشتق و تعریف آن (۵۰ سوال)
    for i in range(1, 51):
        n = (i % 6) + 2
        opts = [f"{to_fa(n)}x^{to_fa(n-1)}", f"x^{to_fa(n-1)}", f"{to_fa(n)}x^{to_fa(n)}", f"{to_fa(n-1)}x^{to_fa(n)}"]
        questions.append(make_q(
            f"مشتق تابع f(x) = x^{to_fa(n)} نسبت به x کدام است؟",
            opts, 0, 12, "math", "متوسط", ["مشتق", "پایه دوازدهم"], 1,
            f"قاعده توان در مشتق: d/dx(x^n) = n * x^(n-۱) -> مشتق برابر {to_fa(n)}x^{to_fa(n-1)} است."
        ))

    # ۲. نقاط بحرانی و اکسترمم (۵۰ سوال)
    for i in range(1, 51):
        opts = ["مشتق برابر صفر است یا وجود ندارد", "تابع ناپیوسته است", "تابع همواره صعودی است", "عرض از مبدا است"]
        questions.append(make_q(
            f"نقطه بحرانی تابع درونی دامنه‌ای است که در آن: (تست {to_fa(i)})",
            opts, 0, 12, "math", "متوسط", ["کاربرد مشتق", "نقاط بحرانی"], 1,
            "نقاطی از دامنه که مشتق در آن‌ها صفر باشد یا مشتق وجود نداشته باشد، نقاط بحرانی نامیده می‌شوند."
        ))

    # ۳. حد در بی‌نهایت و مجانب‌ها (۵۰ سوال)
    for i in range(1, 51):
        opts = ["مجانب افقی", "مجانب قائم", "مجانب مایل", "نقطه عطف"]
        questions.append(make_q(
            f"اگر حد تابع f(x) وقتی x به سمت بی‌نهایت میل می‌کند برابر عددی ثابت مثل L شود، خط y = L چه نام دارد؟ (تست {to_fa(i)})",
            opts, 0, 12, "math", "متوسط", ["حد در بی‌نهایت", "مجانب افقی"], 1,
            "حد در بی‌نهایت خط مجانب افقی تابع را مشخص می‌کند."
        ))

    # ۴. بهینه‌سازی و آزمون مشتق دوم (۵۰ سوال)
    for i in range(1, 51):
        opts = ["نقطه مینیمم موضعی", "نقطه ماکزیمم موضعی", "نقطه عطف قطعی", "نقطه ناپیوستگی"]
        questions.append(make_q(
            f"اگر در یک نقطه بحرانی c داشته باشیم f'(c) = ۰ و f''(c) > ۰، این نقطه کدام است؟ (تست {to_fa(i)})",
            opts, 0, 12, "math", "سخت", ["آزمون مشتق دوم", "بهینه‌سازی"], 1,
            "طبق آزمون مشتق دوم، مثبت بودن مشتق دوم در نقطه با مشتق صفر نشانه مینیمم نسبی است."
        ))

    return questions
