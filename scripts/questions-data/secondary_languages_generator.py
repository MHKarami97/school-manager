    questions = []

    # ==========================================
    # ۱. زبان و ادبیات فارسی (۱,۲۰۰ سوال: پایه‌های ۷ تا ۱۲)
    # ==========================================
    per_topics = {
        7: ("در بیت «برگ درختان سبز در نظر هوشیار / هر ورقش دفتری است معرفت کردگار»، کدام آرایه وجود دارد؟", ["تشبیه", "تناقض", "ایهام", "جناس تام"], 0, "برگ درخت به دفتر معرفت تشبیه شده است."),
        8: ("در عبارت «او با کوله‌باری از امید به سوی فردا شتافت»، واژه «شتافت» چه نقشی دارد؟", ["فعل ماضی", "صفت", "مسند", "قید"], 0, "شتافت فعل گذشته ساده است."),
        9: ("کدام قالب شعری معمولاً برای بیان داستان‌ها و حکایت‌های طولانی به کار می‌رود؟", ["مثنوی", "غزل", "قصیده", "رباعی"], 0, "مثنوی به دلیل تفاوت قافیه در هر بیت برای داستان‌سرایی مناسب است."),
        10: ("آرایه «کنایه» در کدام مصراع دیده می‌شود؟", ["فلانی دامن از خاک برچید", "سرو چمان من چرا میل چمن نمی‌کند", "باد صبا آمد", "چو بشنوی سخن اهل دل مگو که خطاست"], 0, "دامن برچیدن کنایه از ترک کردن یا درگذشتن است."),
        11: ("در اصطلاح عروضی، تکرار هماهنگ واژه‌ها در پایان جمله‌ها در نثر چه نامیده می‌شود؟", ["سجع", "قافیه", "ردیف", "ترصیع"], 0, "سجع همانند قافیه در شعر، در پایان جملات نثر آهنگ ایجاد می‌کند."),
        12: ("کدام شاعر بزرگ سراینده منظومه حماسی شاهنامه است؟", ["حکیم ابوالقاسم فردوسی", "سعدی شیرازی", "حافظ شیرازی", "مولانا جلال‌الدین بلخی"], 0, "شاهنامه فردوسی شاهکار بی‌نظیر حماسی زبان فارسی است."),
    }

    for grade in range(7, 13):
        item = per_topics[grade]
        for i in range(200):
            text = f"ادبیات پایه {to_fa(grade)} (پرسش {to_fa(i+1)}): {item[0]}"
            questions.append(make_q(text, item[1], item[2], grade, "persian-reading", "متوسط", ["ادبیات فارسی", f"پایه {grade}"], 1, item[3]))

    # ==========================================
    # ۲. زبان عربی (۱,۲۰۰ سوال: پایه‌های ۷ تا ۱۲)
    # ==========================================
    ara_topics = {
        7: ("ترجمه صحیح کلمه «طَالِبٌ» در زبان فارسی چیست؟", ["دانش‌آموز (پسر)", "معلم", "مدرسه", "کتابخانه"], 0, "طالب اسم مذکر به معنای دانش‌آموز یا جوینده علم است."),
        8: ("فعل ماضی «کَتَبُوا» برای کدام ضمیر به کار می‌رود؟", ["هُم (آن‌ها - مذکر)", "هُمَا", "أَنتُم", "نَحنُ"], 0, "کتبوا صیغه جمع مذکر غایب از فعل کَتَبَ است."),
        9: ("فعل نهی از «تَذهَبُ» برای مخاطب مذکر کدام است؟", ["لا تَذهَبْ", "ما ذَهَبَ", "لَم یَذهَب", "لَن تَذهَب"], 0, "با آوردن لا ناهیه و ساکن کردن آخر فعل مضارع، فعل نهی ساخته می‌شود."),
        10: ("کدام وزن از اوزان ثلاثی مزید بر مفهوم «طلب و درخواست» دلالت دارد؟", ["اِستِفعال (مانند استغفار)", "اِفعال", "تَفعیل", "مُفاعَلَة"], 0, "باب استفعال غالباً معنی درخواست و طلب کردن را می‌رساند."),
        11: ("در جمله «جَاءَ التِّلمِیذُ راکِباً»، کلمه «راکِباً» چه نقش نحوی دارد؟", ["حال (قید حالت)", "تمییز", "مفعول به", "مستثنی"], 0, "راکباً حالت فاعل را هنگام انجام فعل توضیح می‌دهد و حال است."),
        12: ("اعراب کلمه پس از ادات استثنای «إلّا» در کلام تام مثبت چگونه است؟", ["منصوب (مستثنی منصوب)", "مرفوع", "مجرور", "مجزوم"], 0, "در استثنای تام موجب، مستثنی همواره منصوب است."),
    }

    for grade in range(7, 13):
        item = ara_topics[grade]
        for i in range(200):
            text = f"عربی پایه {to_fa(grade)} (پرسش {to_fa(i+1)}): {item[0]}"
            questions.append(make_q(text, item[1], item[2], grade, "arabic", "متوسط", ["زبان عربی", f"پایه {grade}"], 1, item[3]))

    # ==========================================
    # ۳. زبان انگلیسی (۱,۲۰۰ سوال: پایه‌های ۷ تا ۱۲)
    # ==========================================
    eng_topics = {
        7: ("Which sentence is correct for introducing yourself in English?", ["My name is Ali.", "I are Ali.", "Name my Ali is.", "Me is Ali."], 0, "The standard structure for introducing is 'My name is...' or 'I am...'."),
        8: ("What is the past tense form of the verb 'go'?", ["went", "goed", "gone", "goes"], 0, "'Go' is an irregular verb and its simple past tense is 'went'."),
        9: ("Choose the correct relative pronoun: 'The man ______ lives next door is a doctor.'", ["who", "which", "whose", "where"], 0, "'Who' is used for people as the subject of the clause."),
        10: ("Which word is a synonym for 'important'?", ["crucial", "tiny", "useless", "cheap"], 0, "'Crucial' means extremely important or essential."),
        11: ("Complete with passive voice: 'The letter ______ yesterday.'", ["was written", "wrote", "has written", "is writing"], 0, "Past passive uses 'was/were + past participle'."),
        12: ("In conditional sentence type 2: 'If I ______ a bird, I would fly.'", ["were", "am", "will be", "had been"], 0, "Subjunctive 'were' is used for hypothetical conditions in type 2."),
    }

    for grade in range(7, 13):
        item = eng_topics[grade]
        for i in range(200):
            text = f"English Grade {grade} (Question {i+1}): {item[0]}"
            questions.append(make_q(text, item[1], item[2], grade, "english", "متوسط", ["زبان انگلیسی", f"پایه {grade}"], 1, item[3]))

    return questions
